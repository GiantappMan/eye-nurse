//! 构建脚本（实现者 D 所有，tauri 架构文档 §3/§10）。
//!
//! 1) theme.json 校验 + 代码生成（§3）：读取配色单一真源 `src/ui/theme.json`，
//!    严格校验（`#RRGGBB` 正则 + 必备键存在，失败即 panic = 编译期红），生成 RGB
//!    常量到 OUT_DIR 供 `ui/theme.rs` `include!`；
//! 2) tauri_build（§10）：窗口/应用图标（仓库根 `assets/logo.ico`）与 app.manifest
//!    （PerMonitorV2）经 tauri-build 嵌入（替代 egui 版的 embed-resource）；
//!    capabilities 校验与 ACL 代码生成一并完成（默认扫 `./capabilities/**/*`）；
//! 3) 一致性差异 #8（清单 H1）：把单一真源
//!    `crates/eyenurse-core/assets/languages/{zh,en}.json` 落到
//!    `target/{profile}/Assets/Languages/`——dev 运行即满足 v2 的“exe 旁
//!    Assets/Languages、替换 json 即换文案”布局；安装包同源拷贝（setup/compile.ps1）。
//!    拷贝为 best-effort：失败不阻塞构建（运行时 load_i18n 回退内嵌副本）。
//!
//! 构建期路径纪律（Mimosa L2 复查项）：所有 std::fs 路径都从 cargo 锚点
//! （CARGO_MANIFEST_DIR / OUT_DIR）**先规范化**出发，只拼装固定分量，读入路径
//! 再做「规范化 + 越界断言」双重校验；不书写任何含相对分量的 fs 路径。

use std::path::{Path, PathBuf};

fn main() {
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed=src/ui/theme.json");
    println!("cargo:rerun-if-changed=app.manifest");
    println!("cargo:rerun-if-changed=../../assets/logo.ico");
    println!("cargo:rerun-if-changed=../eyenurse-core/assets/languages/zh.json");
    println!("cargo:rerun-if-changed=../eyenurse-core/assets/languages/en.json");

    generate_theme_consts();
    copy_languages_next_to_exe();
    tauri_build();
}

// ============================================================================
// 构建期路径校验（Mimosa L2 复查项：路径穿越纵深防御）
// ============================================================================

/// cargo 锚点统一入口：环境变量先规范化为绝对路径（解析符号链接），此后一切
/// fs 拼装都发生在规范化结果上；不可达即 panic（编译期红）。输入来自 cargo 与
/// 本文件的固定字面量，不存在运行时不可信输入——校验是纵深防御与自检（落点
/// 漂移立刻编译失败）。
fn canonicalized(path: &Path) -> PathBuf {
    path.canonicalize()
        .unwrap_or_else(|e| panic!("构建期路径不可达（{}）: {e}", path.display()))
}

/// 断言 `path`（应已规范化）落在 `root`（应已规范化）之内；越界即 panic。
fn assert_within(path: &Path, root: &Path) {
    assert!(
        path.starts_with(root),
        "构建期路径越界：{} 不在 {} 之内",
        path.display(),
        root.display()
    );
}

/// 两个 cargo 锚点（已规范化）：crate 目录与 OUT_DIR
struct Anchors {
    manifest_dir: PathBuf,
    out_dir: PathBuf,
}

impl Anchors {
    fn from_env() -> Self {
        Self {
            manifest_dir: canonicalized(&PathBuf::from(
                std::env::var("CARGO_MANIFEST_DIR").unwrap_or_default(),
            )),
            out_dir: canonicalized(&PathBuf::from(
                std::env::var("OUT_DIR").unwrap_or_default(),
            )),
        }
    }
}

// ============================================================================
// 1) theme.json → Rust 常量（§3；唯一允许的改色入口 = 改 theme.json）
// ============================================================================

/// 必备键（缺失 = 编译失败，防跨所有者漂移）；值必须匹配 `#RRGGBB`
const THEME_KEYS: &[&str] = &[
    "mask_bg",
    "mask_fg",
    "mask_error",
    "bar_progress_bg",
    "bar_text_idle",
    "bar_progress_fill",
    "bar_check_glyph",
    "bar_check_hover_bg",
    "bar_progress_from",
    "bar_progress_to",
    "bar_text_from",
    "bar_text_to",
];

fn generate_theme_consts() {
    let anchors = Anchors::from_env();

    // 读入路径 = 已规范化 crate 目录 + 固定分量；规范化后断言仍在 crate 目录内
    let path = canonicalized(&anchors.manifest_dir.join("src/ui/theme.json"));
    assert_within(&path, &anchors.manifest_dir);
    let text = std::fs::read_to_string(&path)
        .unwrap_or_else(|e| panic!("读取 theme.json 失败（{}）: {e}", path.display()));
    let json: serde_json::Map<String, serde_json::Value> = serde_json::from_str(&text)
        .unwrap_or_else(|e| panic!("theme.json 不是合法 JSON 对象: {e}"));

    let mut code = String::from("// @generated by build.rs from src/ui/theme.json —— 勿手改本文件\n");
    for key in THEME_KEYS {
        let value = json
            .get(*key)
            .and_then(|v| v.as_str())
            .unwrap_or_else(|| panic!("theme.json 缺必备键 {key:?}（C 所有的配色真源被破坏）"));
        let (r, g, b) = parse_rrggbb(key, value);
        code.push_str(&format!(
            "pub const {}: Rgb = Rgb::new(0x{r:02X}, 0x{g:02X}, 0x{b:02X});\n",
            key.to_ascii_uppercase()
        ));
    }
    // 产出路径 = 已规范化 OUT_DIR + 固定文件名（无路径分隔符）
    let dest = anchors.out_dir.join("eyenurse_theme_consts.rs");
    std::fs::write(&dest, code)
        .unwrap_or_else(|e| panic!("写出 {} 失败: {e}", dest.display()));
}

/// `#RRGGBB` 严格校验（正则 `^#[0-9A-Fa-f]{6}$` 的手写等价），返回 (r, g, b)
fn parse_rrggbb(key: &str, value: &str) -> (u8, u8, u8) {
    fn hex2(s: &str) -> Option<u8> {
        u8::from_str_radix(s, 16).ok()
    }
    let body = value.strip_prefix('#').unwrap_or("");
    if body.len() == 6 && body.bytes().all(|b| b.is_ascii_hexdigit()) {
        if let (Some(r), Some(g), Some(b)) = (hex2(&body[0..2]), hex2(&body[2..4]), hex2(&body[4..6]))
        {
            return (r, g, b);
        }
    }
    panic!("theme.json 的 {key:?} = {value:?} 不是合法的 #RRGGBB 颜色");
}

// ============================================================================
// 3) 语言文件拷贝（egui 版 build.rs 的职责保留；实现改为内嵌内容直写）
// ============================================================================

/// 单一真源（含路径锚定）：编译期直接嵌入 core 的语言文件。真源文件就在仓库
/// 固定位置，include_str! 宏在编译期读取——运行期 fs 不再接触任何含相对分量
/// 的路径，拷贝内容与真源逐字节一致。
const ZH_JSON: &str = include_str!("../eyenurse-core/assets/languages/zh.json");
const EN_JSON: &str = include_str!("../eyenurse-core/assets/languages/en.json");

/// OUT_DIR = target/{profile}/build/eyenurse-app-<hash>/out，三级祖先即 {profile} 目录
fn target_profile_dir() -> Option<PathBuf> {
    let out = PathBuf::from(std::env::var_os("OUT_DIR")?);
    out.ancestors().nth(3).map(Path::to_path_buf)
}

fn copy_languages_next_to_exe() {
    let Some(dest_root) = target_profile_dir() else {
        return;
    };
    // 落点 = 已规范化 target/{profile} 目录 + 固定分量
    let dest_dir = canonicalized(&dest_root).join("Assets").join("Languages");
    // best-effort：失败不阻塞构建（运行时 load_i18n 回退内嵌副本）
    if std::fs::create_dir_all(&dest_dir).is_ok() {
        for (name, text) in [("zh.json", ZH_JSON), ("en.json", EN_JSON)] {
            let _ = std::fs::write(dest_dir.join(name), text);
        }
    }
}

// ============================================================================
// 2) tauri_build（图标/manifest/capabilities ACL；embed-resource 已移除）
// ============================================================================

fn tauri_build() {
    // window_icon_path 相对构建脚本 cwd（= crate 根）解析 → 仓库根 assets/logo.ico
    //（字符串由 tauri-build 消费，非本脚本 fs 操作）；app_manifest 传 manifest
    // **内容**（include_str!，tauri-build lib.rs:451 注记同款）
    tauri_build::try_build(
        tauri_build::Attributes::new().windows_attributes(
            tauri_build::WindowsAttributes::new()
                .app_manifest(include_str!("app.manifest"))
                .window_icon_path("../../assets/logo.ico"),
        ),
    )
    .expect("tauri_build 失败（检查 tauri.conf.json / capabilities / 图标路径）");
}
